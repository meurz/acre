/// Infer a category from an extension; unknown extensions map to Other.
pub fn category_of(ext: &str) -> Category {
    if ext.is_empty() {
        return Category::Other;
    }
    for (e, c) in KNOWN {
        if *e == ext {
            return *c;
        }
    }
    // Split archive extensions 001, 002, etc. are archives.
    if ext.len() == 3 && ext.bytes().all(|b| b.is_ascii_digit()) {
        return Category::Archive;
    }
    Category::Other
}
