//! Extension categories for treemap colors.

/// Eight treemap categories plus Other, in palette slot order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[repr(u8)]
pub enum Category {
    Program = 0,
    Video = 1,
    Image = 2,
    Archive = 3,
    Audio = 4,
    Document = 5,
    Code = 6,
    System = 7,
    Other = 8,
}

pub const CATEGORY_COUNT: usize = 9;

impl Category {
    pub const ALL: [Category; CATEGORY_COUNT] = [
        Category::Program,
        Category::Video,
        Category::Image,
        Category::Archive,
        Category::Audio,
        Category::Document,
        Category::Code,
        Category::System,
        Category::Other,
    ];
    pub fn label(self) -> &'static str {
        match self {
            Category::Program => "Programs and libraries",
            Category::Video => "Video",
            Category::Image => "Images",
            Category::Archive => "Archives and disk images",
            Category::Audio => "Audio",
            Category::Document => "Documents",
            Category::Code => "Code",
            Category::System => "System and data",
            Category::Other => "Other",
        }
    }
    pub fn index(self) -> usize {
        self as usize
    }
}

